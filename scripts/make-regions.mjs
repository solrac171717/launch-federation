// Generates assets/regions/<CC>.js: the first-level divisions (states, provinces, autonomous communities, regions) of each
// country the app can place assets in, used by the Country view's drill-down (country -> region -> city).
// Source: Natural Earth 1:10m admin-1 (public domain), downloaded once into tmp/ (git-ignored). Run with `npm run make-regions`; the output is committed.
// Spain, Italy, France and the UK are merged up from provinces/departments/districts into the regions people actually name.
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { geoBounds, geoCentroid, geoContains } from 'd3-geo';
import { CITIES_LIST } from '../src/places.js';
import { merge } from 'topojson-client';
import { topology } from 'topojson-server';
import { presimplify, simplify, quantile } from 'topojson-simplify';

const SRC = 'tmp/ne_10m_admin_1_states_provinces.geojson';
const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_admin_1_states_provinces.geojson';
try { await access(SRC); } catch {
  await mkdir('tmp', { recursive: true });
  const r = await fetch(URL); if (!r.ok) throw new Error(`download failed: ${r.status}`);
  await writeFile(SRC, Buffer.from(await r.arrayBuffer()));
}
const fc = JSON.parse(await readFile(SRC, 'utf8'));

// keep the mainland only, like the country outlines (drops overseas departments, far islands, Alaska and Hawaii)
const WIN = {
  US: [-125.5, 24, -66, 49.8], CA: [-141, 41.5, -52, 70], MX: [-118.5, 14.4, -86.5, 32.8], BR: [-74, -34, -34, 5.5], GB: [-8.8, 49.7, 2, 59], IE: [-10.7, 51.3, -5.9, 55.5],
  PT: [-9.7, 36.8, -6.1, 42.2], ES: [-9.5, 35.9, 4.5, 43.9], FR: [-5.5, 41, 9.7, 51.2], DE: [5.8, 47.2, 15.1, 55.1], IT: [6.6, 36.6, 18.6, 47.1], NL: [3.2, 50.7, 7.3, 53.6],
  CH: [5.9, 45.8, 10.6, 47.9], AE: [51.5, 22.5, 56.5, 26.2], AU: [112, -44, 154, -10], NZ: [166, -47.5, 179, -34], JP: [129, 31, 146, 45.6],
};
const UK = { 'Eastern': 'Eastern Scotland', 'South Western': 'South Western Scotland', 'North Eastern': 'North Eastern Scotland', 'East': 'East of England' };
const GROUP = {
  ES: p => p.region, IT: p => p.region, FR: p => p.region,
  GB: p => UK[p.region] || p.region,
  NZ: p => (['North Island', 'South Island'].includes(p.region) ? p.region : null),
};
const nameOf = p => p.name_en && !/^[\u0000-\u007f]*$/.test(p.name) ? p.name : p.name; // native names read best (Cataluña, Île-de-France)

const inWin = (ring, win) => {
  const [lo, la] = ring.reduce((a, c) => [a[0] + c[0] / ring.length, a[1] + c[1] / ring.length], [0, 0]);
  return lo >= win[0] && lo <= win[2] && la >= win[1] && la <= win[3];
};
const features = [];
for (const f of fc.features) {
  const cc = f.properties.iso_a2; if (!WIN[cc]) continue;
  const key = (GROUP[cc] || (p => p.name))(f.properties); if (!key) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const keep = polys.filter(p => inWin(p[0], WIN[cc])); if (!keep.length) continue;
  features.push({ type: 'Feature', properties: { cc, key }, geometry: { type: 'MultiPolygon', coordinates: keep } });
}

const out = {}, report = {};
for (const cc of Object.keys(WIN)) {
  const fs = features.filter(f => f.properties.cc === cc);
  let topo = topology({ a: { type: 'FeatureCollection', features: fs } }, 1e5);
  topo = presimplify(topo);
  const w = quantile(topo, ['US', 'CA', 'BR', 'AU', 'MX'].includes(cc) ? 0.22 : 0.34);
  topo = simplify(topo, w);
  const geoms = topo.objects.a.geometries;
  const groups = new Map();
  geoms.forEach((g, i) => { const k = fs[i].properties.key; (groups.get(k) || groups.set(k, []).get(k)).push(g); });
  const regions = [];
  for (const [name, gs] of groups) {
    const m = merge(topo, gs); // exact dissolve: shared borders vanish
    const polys = m.type === 'Polygon' ? [m.coordinates] : m.coordinates;
    const rings = polys.flatMap(p => p.slice(0, 1)).map(r => { const flat = []; let last = null; for (const c of r) { const x = Math.round(c[0] * 400) / 400, y = Math.round(c[1] * 400) / 400; if (!last || x !== last[0] || y !== last[1]) { flat.push(x, y); last = [x, y]; } } return flat; }).filter(r => r.length >= 8);
    if (!rings.length) continue;
    const g = { type: 'MultiPolygon', coordinates: polys };
    const [[bw, bs], [be, bn]] = geoBounds(g); const [clo, cla] = geoCentroid(g);
    regions.push({ n: nameOf({ name }), b: [Math.round(bw * 100) / 100, Math.round(bs * 100) / 100, Math.round(be * 100) / 100, Math.round(bn * 100) / 100], c: [Math.round(cla * 1000) / 1000, Math.round(clo * 1000) / 1000], r: rings });
  }
  regions.sort((a, b) => a.n.localeCompare(b.n));
  out[cc] = regions; report[cc] = regions.length;
}
await mkdir('assets/regions', { recursive: true });
let total = 0;
for (const [cc, regions] of Object.entries(out)) {
  const body = `// Generated by scripts/make-regions.mjs from Natural Earth admin-1 (public domain). Do not edit.\nexport default ${JSON.stringify(regions)};\n`;
  await writeFile(`assets/regions/${cc}.js`, body); total += body.length;
}
// The outlines are simplified, so a point right on a border (Manhattan sits against New Jersey) can land on the wrong side.
// The cities people pick from the built-in list are therefore placed once, here, against the full-resolution outlines.
const exact = {};
for (const c of CITIES_LIST) {
  const [, , cc, lat, lon] = c; if (!WIN[cc]) continue;
  const f = features.find(x => x.properties.cc === cc && geoContains(x.geometry, [lon, lat]));
  if (f) exact[`${lat.toFixed(2)},${lon.toFixed(2)}`] = f.properties.key;
}
await writeFile('assets/regions/cities.js', `// Generated by scripts/make-regions.mjs. Region of each built-in city, from the full-resolution outlines. Do not edit.\nexport default ${JSON.stringify(exact)};\n`);
console.log('regions per country:', JSON.stringify(report), '\ntotal bytes:', total);
