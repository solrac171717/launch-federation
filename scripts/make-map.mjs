// Generates assets/world-map.js: a dot-matrix map (Natural Earth land) plus projected marker positions.
// Run once with `npm run make-map`; the output is committed so the site needs no map SDK at runtime.
import { readFile, writeFile } from 'node:fs/promises';
import { geoNaturalEarth1, geoContains } from 'd3-geo';
import { feature } from 'topojson-client';
import { CITIES } from '../src/demo-data.js';

const topo = JSON.parse(await readFile('node_modules/world-atlas/countries-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const W = 960, H = 400, STEP = 6.5;
// Fit to the projected bounding box of the lon/lat window (sampled densely: its edges aren't straight lines).
const LON = [-128, 64], LAT = [8, 62];
const edge = [];
for (let t = 0; t <= 1; t += 0.02) {
  const lon = LON[0] + t * (LON[1] - LON[0]), lat = LAT[0] + t * (LAT[1] - LAT[0]);
  edge.push([lon, LAT[0]], [lon, LAT[1]], [LON[0], lat], [LON[1], lat]);
}
const proj = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], { type: 'MultiPoint', coordinates: edge });

let d = '';
let n = 0;
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const ll = proj.invert([x, y]);
    if (!ll || ll[0] < LON[0] || ll[0] > LON[1] || ll[1] < LAT[0] || ll[1] > LAT[1]) continue;
    if (geoContains(land, ll)) { d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`; n++; }
  }
}
const markers = {};
for (const [id, [lat, lon]] of Object.entries(CITIES)) {
  const [x, y] = proj([lon, lat]);
  markers[id] = [+x.toFixed(1), +y.toFixed(1)];
}
const out = `// Generated by scripts/make-map.mjs — do not edit.\nexport const WORLD_MAP = ${JSON.stringify({ w: W, h: H, dots: d, markers })};\n`;
await writeFile('assets/world-map.js', out);
console.log(`dots: ${n}, bytes: ${out.length}`);

// Land points on a Fibonacci sphere, for the rotating 3D globe (lat/lon in degrees, 1 decimal).
{
  const N = 14000, pts = [];
  const golden = Math.PI * (3 - Math.sqrt(5));
  for (let i = 0; i < N; i++) {
    const y = 1 - (i / (N - 1)) * 2, lat = Math.asin(y) * 180 / Math.PI, lon = ((i * golden * 180 / Math.PI + 540) % 360) - 180;
    if (lat < -58) continue;
    if (geoContains(land, [lon, lat])) pts.push(+lat.toFixed(1), +lon.toFixed(1));
  }
  await writeFile('assets/globe-points.js', `// Generated by scripts/make-map.mjs — do not edit.\nexport const GLOBE_POINTS = new Float32Array(${JSON.stringify(pts)});\n`);
  console.log('globe points:', pts.length / 2);
}
